import { extractYouTubeId, normalizeSafeUrl, stripTranscriptTimestamps } from './notes.js';

/**
 * Fetches a clean, timestamp-free YouTube transcript via the local Vite `/api/fetch-transcript` endpoint.
 */
export async function fetchYouTubeTranscript(rawUrl) {
  const safeUrl = normalizeSafeUrl(rawUrl);
  const videoId = extractYouTubeId(safeUrl);
  if (!videoId) {
    throw new Error('Enter a valid YouTube video URL first (e.g., https://www.youtube.com/watch?v=...).');
  }

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 15000);
  try {
    const res = await fetch(`./api/fetch-transcript?url=${encodeURIComponent(safeUrl)}`, {
      signal: controller.signal,
    });
    const contentType = res.headers.get('content-type') || '';
    if (!contentType.includes('application/json')) {
      throw new Error(
        'Automatic transcript fetching requires running the local Vite dev/preview server. You can still paste any transcript below and click "Clean Timestamps".'
      );
    }
    const data = await res.json();
    if (!res.ok || !data?.ok || !data?.transcript) {
      throw new Error(
        data?.error ||
          'No captions/transcript available for this video. You can paste a transcript manually and click "Clean Timestamps".'
      );
    }
    const cleanTranscript = stripTranscriptTimestamps(data.transcript);
    if (!cleanTranscript) {
      throw new Error('Captions were empty for this video.');
    }
    return {
      videoId: data.videoId || videoId,
      title: String(data.title || '').trim(),
      language: String(data.language || 'en'),
      isAutoGenerated: Boolean(data.isAutoGenerated),
      transcript: cleanTranscript,
    };
  } catch (err) {
    if (err?.name === 'AbortError') {
      throw new Error('Transcript request timed out. Try again or paste the transcript manually.');
    }
    throw err;
  } finally {
    clearTimeout(timer);
  }
}
